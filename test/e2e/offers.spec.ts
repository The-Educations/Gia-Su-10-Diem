  const pc = await browser.newContext(), parent = await pc.newPage();
  const errors: string[] = []; page.on("pageerror",e=>errors.push(e.message)); tutor.on("pageerror",e=>errors.push(e.message));
  await login(tutor, "chau");
  const original = await (await tutor.request.get("/api/tutor/profile")).json();
